// scripts/generate-sitemap.js
// Writes public/sitemap.xml from the student tools in src/data/tools.js.
// Runs automatically before `npm run build` (the "prebuild" npm script), so
// the sitemap always lists every student tool, with lastmod = build date.
//
// src/data/tools.js is plain JS (no JSX); its tool components are
// lazy(() => import(...)) wrappers that are never called here, so importing
// it in Node only loads the metadata.

/* global process */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { toolDefinitions, isStudentTool } from "../src/data/tools.js";

const SITE_URL = "https://martyweissman.github.io/modeling-synthesizer/";
const outFile = fileURLToPath(new URL("../public/sitemap.xml", import.meta.url));

const escapeXml = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const studentToolIds = Object.entries(toolDefinitions)
  .filter(([, tool]) => isStudentTool(tool))
  .map(([id]) => id);

if (studentToolIds.length === 0) {
  console.error("generate-sitemap: no student tools found in src/data/tools.js");
  process.exit(1);
}

const lastmod = new Date().toISOString().slice(0, 10);

const urlEntry = (loc, changefreq, priority) => `  <url>
    <loc>${escapeXml(loc)}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`;

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap.js at build time. Do not edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${[
  urlEntry(SITE_URL, "weekly", "1.0"),
  ...studentToolIds.map((id) =>
    urlEntry(`${SITE_URL}?tool=${encodeURIComponent(id)}`, "monthly", "0.8"),
  ),
].join("\n")}
</urlset>
`;

writeFileSync(outFile, xml);
console.log(
  `generate-sitemap: wrote ${studentToolIds.length + 1} URLs to public/sitemap.xml`,
);
